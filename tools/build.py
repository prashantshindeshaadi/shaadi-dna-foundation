#!/usr/bin/env python3
"""
Generate platform files from tokens/.

    python3 tools/build.py

Writes dist/, which is git-ignored on purpose: tokens/ is the only copy of the
data. Run this in CI or locally before publishing the package.
"""
import sys, os, json, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib import all_collections, resolve, var_name, ROOT

OUT = os.path.join(ROOT, "dist")
THEMED = {"sh-color-common", "sh-translucent", "sh-shadow"}
RESPONSIVE = {"sh-typo", "sh-space"}
BREAKPOINTS = {"Tablet": 768, "Desktop": 1024}


def css_value(value, vtype, coll, key):
    if vtype == "color":
        h, a = value["hex"], round(value.get("alpha", 1), 3)
        if a >= 1:
            return h
        r, g, b = (int(h[i:i + 2], 16) for i in (1, 3, 5))
        return f"rgba({r}, {g}, {b}, {a})"
    if vtype == "number":
        n = round(float(value), 3)
        num = str(int(n)) if n.is_integer() else str(n)
        if coll == "sh-opacity":
            return str(round(n / 100, 3))
        if key.startswith("weight/") or key.endswith("/weight"):
            return num
        return num + "px"
    return str(value)


def block(data, coll, mode, indent):
    out = []
    if coll == "sh-color-basic":
        return out
    for key in data[coll]["tokens"]:
        value, vtype = resolve(data, coll, mode, key)
        out.append(f"{indent}{var_name(coll, key)}: {css_value(value, vtype, coll, key)};")
    return out


def build_css(data):
    L = ["/* Shaadi DNA Foundation. Generated by tools/build.py, do not edit. */", "", ":root {"]
    for coll in sorted(data):
        if coll in THEMED or coll in RESPONSIVE or coll == "sh-color-basic":
            continue
        L += [f"  /* {coll} */"] + block(data, coll, "Value", "  ")
    for coll in sorted(THEMED):
        L += [f"  /* {coll} (Light) */"] + block(data, coll, "Light", "  ")
    for coll in sorted(RESPONSIVE):
        L += [f"  /* {coll} (Mobile) */"] + block(data, coll, "Mobile", "  ")
    L += ["}", ""]
    dark = [l for coll in sorted(THEMED) for l in block(data, coll, "Dark", "    ")]
    L += ["@media (prefers-color-scheme: dark) {", "  :root:not([data-theme='light']) {"] + dark + ["  }", "}", ""]
    L += ["[data-theme='dark'] {"] + [l[2:] for l in dark] + ["}", ""]
    for mode, px in BREAKPOINTS.items():
        rows = [l for coll in sorted(RESPONSIVE) for l in block(data, coll, mode, "    ")]
        L += [f"@media (min-width: {px}px) {{", "  :root {"] + rows + ["  }", "}", ""]
    return "\n".join(L)


def build_json(data):
    flat = {}
    for coll, c in data.items():
        if coll == "sh-color-basic":
            continue
        for key, t in c["tokens"].items():
            entry = {"type": t["type"], "css": var_name(coll, key),
                     "description": t.get("description", "").split("\n", 1)[-1], "values": {}}
            for mode in c["modes"]:
                v, vt = resolve(data, coll, mode, key)
                entry["values"][mode] = css_value(v, vt, coll, key)
            flat[f"{coll}/{key}"] = entry
    return json.dumps(flat, indent=2, ensure_ascii=False)


def build_android(data):
    files = {}

    def colors(mode):
        rows = []
        for coll in ("sh-color-common", "sh-translucent"):
            for key in data[coll]["tokens"]:
                v, vt = resolve(data, coll, mode, key)
                if vt != "color":
                    continue
                a = v.get("alpha", 1)
                argb = v["hex"] if a >= 1 else f"#{int(round(a*255)):02X}{v['hex'][1:]}"
                rows.append(f'    <color name="{var_name(coll,key)[2:].replace("-","_")}">{argb}</color>')
        return '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n' + "\n".join(rows) + "\n</resources>\n"

    def dims(pairs):
        rows = []
        for coll, mode in pairs:
            for key in data[coll]["tokens"]:
                v, vt = resolve(data, coll, mode, key)
                if vt != "number":
                    continue
                unit = "sp" if coll == "sh-typo" else "dp"
                val = css_value(v, vt, coll, key).replace("px", "")
                rows.append(f'    <dimen name="{var_name(coll,key)[2:].replace("-","_")}">{val}{unit}</dimen>')
        return '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n' + "\n".join(rows) + "\n</resources>\n"

    files["values/sh_colors.xml"] = colors("Light")
    files["values-night/sh_colors.xml"] = colors("Dark")
    files["values/sh_dimens.xml"] = dims([("sh-space", "Mobile"), ("sh-typo", "Mobile"),
                                          ("sh-radius", "Value"), ("sh-stroke", "Value"), ("sh-icon", "Value")])
    files["values-sw600dp/sh_dimens.xml"] = dims([("sh-space", "Tablet"), ("sh-typo", "Tablet")])
    files["values-sw840dp/sh_dimens.xml"] = dims([("sh-space", "Desktop"), ("sh-typo", "Desktop")])
    return files


def build_swift(data):
    ident = lambda k: (lambda p: p[0].lower() + "".join(x.capitalize() for x in p[1:]))(
        [x for x in re.split(r"[^a-zA-Z0-9]+", k) if x])
    L = ["// Shaadi DNA Foundation. Generated by tools/build.py, do not edit.",
         "import SwiftUI", "", "public enum SH {", "", "    public enum Color {"]
    for coll in ("sh-color-common", "sh-translucent"):
        for key in data[coll]["tokens"]:
            l, vt = resolve(data, coll, "Light", key)
            d, _ = resolve(data, coll, "Dark", key)
            if vt != "color":
                continue
            name = ident(key if coll == "sh-color-common" else "translucent/" + key)
            L.append(f'        public static let {name} = SHColor(light: "{l["hex"]}", lightAlpha: {round(l.get("alpha",1),3)}, '
                     f'dark: "{d["hex"]}", darkAlpha: {round(d.get("alpha",1),3)})')
    L += ["    }", ""]
    for coll, mode, group in (("sh-space", "Mobile", "Space"), ("sh-radius", "Value", "Radius"),
                              ("sh-stroke", "Value", "Stroke"), ("sh-icon", "Value", "Icon"),
                              ("sh-typo", "Mobile", "Type"), ("sh-opacity", "Value", "Opacity")):
        L.append(f"    public enum {group} {{")
        for key in data[coll]["tokens"]:
            v, vt = resolve(data, coll, mode, key)
            if vt != "number":
                continue
            L.append(f"        public static let {ident(key)}: CGFloat = {css_value(v, vt, coll, key).replace('px','')}")
        L += ["    }", ""]
    return "\n".join(L + ["}"]) + "\n"


def write(path, content):
    full = os.path.join(OUT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w").write(content)
    print(f"  dist/{path}  ({len(content):,} bytes)")


def main():
    data = all_collections()
    print(f"Building from {sum(len(c['tokens']) for c in data.values())} variables")
    write("css/tokens.css", build_css(data))
    write("json/tokens.json", build_json(data))
    for name, content in build_android(data).items():
        write("android/" + name, content)
    write("ios/SHTokens.swift", build_swift(data))
    print("Done.")


if __name__ == "__main__":
    main()
