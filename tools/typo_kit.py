#!/usr/bin/env python3
"""
Build the sh-typo kit: fonts + typography code for designers, web, Android, iOS.

    python3 tools/typo_kit.py          (also run by tools/build.py)

Reads tokens/sh-typo.json and fonts/. Writes dist/sh-typo-kit/ and
dist/sh-typo-kit.zip, the file to share with the team. The kit README is
fonts/README.md plus a generated table of weights and styles.
"""
import sys, os, re, json, shutil, zipfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib import all_collections, resolve, var_name, ROOT
from export_figma import to_figma

FONTS = os.path.join(ROOT, "fonts")
OUT = os.path.join(ROOT, "dist", "sh-typo-kit")
MODES = ["Mobile", "Tablet", "Desktop"]
WEIGHTS = ["regular", "medium", "bold", "black"]


def camel(s):
    return re.sub(r"-(\w)", lambda m: m.group(1).upper(), s)


def num(x):
    x = round(float(x), 4)
    return str(int(x)) if x.is_integer() else str(x)


# id, label, token prefix for font/weight/size/tracking, prefix for line height, uppercase
STYLES = [("display", "Display", "display", "display", False)]
STYLES += [(f"heading-{s}", f"Heading {s.upper()}", f"heading/{s}", f"heading/{s}", False) for s in ("lg", "md", "sm")]
STYLES += [(f"title-{s}", f"Title {s.upper()}", f"title/{s}", f"title/{s}", False) for s in ("lg", "md", "sm")]
STYLES += [(f"body-{s}" + ("" if v == "default" else f"-{v}"),
            f"Body {s.upper()}" + ("" if v == "default" else f" {v.capitalize()}"),
            f"body/{s}/default", f"body/{s}/{v}", False)
           for s in ("lg", "md", "sm") for v in ("default", "tight", "loose")]
STYLES += [(f"support-{s}", f"Support {s.capitalize()}", f"support/{s}", f"support/{s}", s == "micro")
           for s in ("label", "micro", "meta")]
STYLES += [(f"button-{s}", f"Button {s.upper()}", f"button/{s}", f"button/{s}", False) for s in ("lg", "md", "sm")]


class Typo:
    def __init__(self, data):
        self.data = data
        self.c = data["sh-typo"]
        self.T = self.c["tokens"]

    def val(self, key, mode):
        return resolve(self.data, "sh-typo", mode, key)[0]

    def styles(self, mode):
        rows = []
        for sid, label, base, lh, upper in STYLES:
            rows.append(dict(
                id=sid, name=camel(sid), label=label, upper=upper, base=base, lh=lh,
                weight_name=self.T[f"{base}/weight"]["values"][mode]["alias"].split("/")[1],
                weight=self.val(f"{base}/weight", mode), size=self.val(f"{base}/size", mode),
                line=self.val(f"{lh}/line-height", mode), track=self.val(f"{base}/letter-spacing", mode)))
        return rows


# ---- web ----------------------------------------------------------------
def css(t):
    family = t.val("font-family/primary", "Mobile")

    def block(mode, only_changing, indent):
        out = []
        for key, e in t.T.items():
            if e["type"] != "number":
                continue
            v = t.val(key, mode)
            if only_changing and v == t.val(key, "Mobile"):
                continue
            unit = "" if key.startswith("weight/") or key.endswith("/weight") else "px"
            out.append(f"{indent}{var_name('sh-typo', key)}: {num(v)}{unit};")
        return out

    L = ["/* Shaadi DNA · sh-typo. Generated by tools/typo_kit.py, do not edit. */", "",
         "@font-face {", f"  font-family: '{family}';",
         "  src: url('fonts/LexendSH-VF.woff2') format('woff2');",
         "  font-weight: 100 900;   /* required, or the custom weights snap to 400/500/600/700 */",
         "  font-style: normal;", "  font-display: swap;", "}", "",
         ":root {", f"  --sh-typo-font-family-primary: '{family}', system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif;"]
    L += block("Mobile", False, "  ") + ["}", ""]
    for mode, px in (("Tablet", 768), ("Desktop", 1024)):
        L += [f"@media (min-width: {px}px) {{", "  :root {"] + block(mode, True, "    ") + ["  }", "}", ""]
    L += ["html { font-synthesis: none; -webkit-font-smoothing: antialiased; }", ""]
    p = lambda k: var_name("sh-typo", k)
    for r in t.styles("Mobile"):
        L += [f".sh-{r['id']} {{", "  font-family: var(--sh-typo-font-family-primary);",
              f"  font-weight: var({p(r['base'] + '/weight')});",
              f"  font-size: var({p(r['base'] + '/size')});",
              f"  line-height: var({p(r['lh'] + '/line-height')});",
              f"  letter-spacing: var({p(r['base'] + '/letter-spacing')});"]
        L += (["  text-transform: uppercase;"] if r["upper"] else []) + ["}", ""]
    return "\n".join(L)


def preview(t):
    rows = "\n".join(
        f'    <tr><td class="m">{r["label"]}<br><code>.sh-{r["id"]}</code></td>'
        f'<td class="m">{num(r["size"])}/{num(r["line"])} · {num(r["weight"])}</td>'
        f'<td><div class="sh-{r["id"]}">Find someone who feels like home</div></td></tr>'
        for r in t.styles("Mobile"))
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>sh-typo preview</title><link rel="stylesheet" href="sh-typo.css">
<style>
  body {{ margin: 0; padding: 24px 16px; color: #0F172A; background: #fff; font-family: var(--sh-typo-font-family-primary); }}
  table {{ border-collapse: collapse; width: 100%; }}
  td {{ border-top: 1px solid #E2E8F0; padding: 12px 8px; vertical-align: top; }}
  .m {{ font-size: 12px; color: #64748B; white-space: nowrap; }}
  td div {{ background: rgba(194, 15, 56, .06); }}
</style></head>
<body>
  <p class="sh-body-md">Shaded area is the line box. Display and Heading change at 768px and 1024px.</p>
  <table>
{rows}
  </table>
</body></html>
"""


# ---- Android (Jetpack Compose) -----------------------------------------
def kotlin(t):
    W = {w: num(t.val(f"weight/{w}", "Mobile")) for w in WEIGHTS}
    fields = "\n".join(f"    val {r['name']}: TextStyle," for r in t.styles("Mobile"))

    def obj(mode):
        rows = [f"        {r['name']} = style({num(r['size'])}, {num(r['line'])}, ShWeight.{r['weight_name'].capitalize()}, {num(r['track'])}),"
                for r in t.styles(mode)]
        return f"    val {mode.lower()} = ShTypographySet(\n" + "\n".join(rows) + "\n    )"

    return f"""// Shaadi DNA · sh-typo. Generated by tools/typo_kit.py, do not edit.
// Fonts: copy res/font/*.ttf into app/src/main/res/font/.
// Set `package` and the `R` import to your app's.

package com.shaadi.dna.typography

import androidx.compose.ui.text.PlatformTextStyle
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.Font
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.LineHeightStyle
import androidx.compose.ui.unit.sp
// import com.shaadi.app.R

object ShWeight {{
    val Regular = FontWeight({W['regular']})
    val Medium = FontWeight({W['medium']})
    val Bold = FontWeight({W['bold']})
    val Black = FontWeight({W['black']})
}}

/** Lexend-SH, four static files: works on every API level. */
val LexendSH = FontFamily(
    Font(R.font.lexendsh_regular, ShWeight.Regular),
    Font(R.font.lexendsh_medium, ShWeight.Medium),
    Font(R.font.lexendsh_bold, ShWeight.Bold),
    Font(R.font.lexendsh_black, ShWeight.Black),
)

private fun style(size: Number, lineHeight: Number, weight: FontWeight, tracking: Number) = TextStyle(
    fontFamily = LexendSH,
    fontWeight = weight,
    fontSize = size.toFloat().sp,
    lineHeight = lineHeight.toFloat().sp,
    letterSpacing = tracking.toFloat().sp,
    // Exact line height, text centred in the line box, as in Figma.
    lineHeightStyle = LineHeightStyle(LineHeightStyle.Alignment.Center, LineHeightStyle.Trim.None),
    platformStyle = PlatformTextStyle(includeFontPadding = false),
)

data class ShTypographySet(
{fields}
)

/**
 * Pick by window width: below 600dp mobile, 600-839dp tablet, 840dp+ desktop.
 * Only Display and Heading differ. Support Micro is uppercase: pass text.uppercase().
 */
object ShTypography {{
{obj('Mobile')}

{obj('Tablet')}

{obj('Desktop')}

    fun forWidth(widthDp: Int): ShTypographySet = when {{
        widthDp >= 840 -> desktop
        widthDp >= 600 -> tablet
        else -> mobile
    }}
}}
"""


# ---- iOS (SwiftUI + UIKit) ---------------------------------------------
def swift(t):
    W = {w: num(t.val(f"weight/{w}", "Mobile")) for w in WEIGHTS}
    cases = "\n".join(f"    case {r['name']}" for r in t.styles("Mobile"))

    def spec(mode):
        return "\n".join(
            f"        case .{r['name']}: return ShTypeSpec(font: .{r['weight_name']}, size: {num(r['size'])}, "
            f"lineHeight: {num(r['line'])}, tracking: {num(r['track'])}, uppercase: {str(r['upper']).lower()})"
            for r in t.styles(mode))

    return f"""// Shaadi DNA · sh-typo. Generated by tools/typo_kit.py, do not edit.
// Fonts: add Fonts/LexendSH-*.ttf to the app target and list them under
// UIAppFonts ("Fonts provided by application") in Info.plist.

import SwiftUI
import UIKit

public enum ShFont: String {{
    case regular = "LexendSH-Regular"   // {W['regular']}
    case medium  = "LexendSH-Medium"    // {W['medium']}
    case bold    = "LexendSH-Bold"      // {W['bold']}
    case black   = "LexendSH-Black"     // {W['black']}
}}

public struct ShTypeSpec {{
    public let font: ShFont
    public let size: CGFloat
    public let lineHeight: CGFloat
    public let tracking: CGFloat
    public let uppercase: Bool
}}

public enum ShTextStyle {{
{cases}

    /// compact width -> mobile, regular width (iPad) -> tablet. desktop: Mac Catalyst / visionOS.
    public enum Breakpoint {{ case mobile, tablet, desktop }}

    public func spec(_ bp: Breakpoint) -> ShTypeSpec {{
        switch bp {{
        case .mobile: return mobile
        case .tablet: return tablet
        case .desktop: return desktop
        }}
    }}

    private var mobile: ShTypeSpec {{
        switch self {{
{spec('Mobile')}
        }}
    }}

    private var tablet: ShTypeSpec {{
        switch self {{
{spec('Tablet')}
        }}
    }}

    private var desktop: ShTypeSpec {{
        switch self {{
{spec('Desktop')}
        }}
    }}
}}

public extension ShTypeSpec {{
    /// Scales with Dynamic Type.
    var uiFont: UIFont {{
        let base = UIFont(name: font.rawValue, size: size) ?? .systemFont(ofSize: size)
        return UIFontMetrics.default.scaledFont(for: base)
    }}

    /// UIKit: exact line height, tracking and case for UILabel.attributedText.
    func attributed(_ text: String) -> NSAttributedString {{
        let f = uiFont
        let lh = UIFontMetrics.default.scaledValue(for: lineHeight)
        let p = NSMutableParagraphStyle()
        p.minimumLineHeight = lh
        p.maximumLineHeight = lh
        return NSAttributedString(string: uppercase ? text.uppercased() : text, attributes: [
            .font: f, .kern: tracking, .paragraphStyle: p, .baselineOffset: (lh - f.lineHeight) / 4,
        ])
    }}
}}

private struct ShTextStyleModifier: ViewModifier {{
    let style: ShTextStyle
    @Environment(\\.horizontalSizeClass) private var sizeClass
    @Environment(\\.dynamicTypeSize) private var dynamicTypeSize   // re-render on change

    func body(content: Content) -> some View {{
        let s = style.spec(sizeClass == .regular ? .tablet : .mobile)
        let f = s.uiFont
        let extra = max(0, UIFontMetrics.default.scaledValue(for: s.lineHeight) - f.lineHeight)
        return content
            .font(Font(f))
            .tracking(s.tracking)
            .lineSpacing(extra)
            .padding(.vertical, extra / 2)
            .textCase(s.uppercase ? .uppercase : nil)
    }}
}}

public extension View {{
    /// SwiftUI: Text("Find someone who feels like home").shTextStyle(.headingLg)
    func shTextStyle(_ style: ShTextStyle) -> some View {{
        modifier(ShTextStyleModifier(style: style))
    }}
}}
"""


# ---- README -------------------------------------------------------------
def readme(t):
    head = open(os.path.join(FONTS, "README.md")).read().rstrip()
    L = [head, "", "---", "", "## Weights", "", "| Name | Value |", "|---|---|"]
    L += [f"| {w.capitalize()} | **{num(t.val(f'weight/{w}', 'Mobile'))}** |" for w in WEIGHTS]
    L += ["", "## The 22 styles", "", "| Style | Weight | Size / line height (Mobile → Tablet → Desktop) |", "|---|---|---|"]
    rows = {m: t.styles(m) for m in MODES}
    for i, r in enumerate(rows["Mobile"]):
        sizes = [f"{num(rows[m][i]['size'])}/{num(rows[m][i]['line'])}" for m in MODES]
        sz = sizes[0] if len(set(sizes)) == 1 else " → ".join(sizes)
        L.append(f"| {r['label']}{' (uppercase)' if r['upper'] else ''} | {r['weight_name'].capitalize()} {num(r['weight'])} | {sz} |")
    return "\n".join(L) + "\n"


def main():
    data = all_collections()
    t = Typo(data)
    if os.path.exists(OUT):
        shutil.rmtree(OUT)
    for d in ("designer/figma-variables", "developer/web/fonts", "developer/android/res/font", "developer/ios/Fonts"):
        os.makedirs(os.path.join(OUT, d))
    cp = lambda src, dst: shutil.copy(os.path.join(FONTS, src), os.path.join(OUT, dst))
    cp("LexendSH-VF.ttf", "designer/LexendSH-VF.ttf")
    cp("LexendSH-VF.woff2", "developer/web/fonts/LexendSH-VF.woff2")
    cp("OFL.txt", "OFL.txt")
    for w in WEIGHTS:
        cp(f"LexendSH-{w.capitalize()}.ttf", f"developer/android/res/font/lexendsh_{w}.ttf")
        cp(f"LexendSH-{w.capitalize()}.ttf", f"developer/ios/Fonts/LexendSH-{w.capitalize()}.ttf")
    for mode in t.c["modes"]:
        json.dump(to_figma(data, "sh-typo", t.c, mode),
                  open(os.path.join(OUT, f"designer/figma-variables/{mode}.tokens.json"), "w"),
                  indent=2, ensure_ascii=False)
    files = {"developer/web/sh-typo.css": css(t), "developer/web/preview.html": preview(t),
             "developer/android/ShTypography.kt": kotlin(t), "developer/ios/ShTypography.swift": swift(t),
             "README.md": readme(t)}
    for path, text in files.items():
        open(os.path.join(OUT, path), "w").write(text)
    z = OUT + ".zip"
    with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
        for root, _, names in os.walk(OUT):
            for n in sorted(names):
                p = os.path.join(root, n)
                zf.write(p, os.path.relpath(p, os.path.dirname(OUT)))
    print(f"  dist/sh-typo-kit.zip  ({os.path.getsize(z):,} bytes, 22 styles)")


if __name__ == "__main__":
    main()
